import { BLIND_LEVELS, defaultOptions } from './rules.js';

const fmt = (n) => n.toLocaleString('ja-JP');

/** @param {Object} [options] そのルームの設定 */
export function rulebook(options) {
  const o = { ...defaultOptions, ...options };
  const levels = BLIND_LEVELS.slice(0, 6).map(([sb, bb]) => `${sb}/${bb}`).join(' → ');
  return [
    {
      title: 'ゲームの目的',
      paras: [
        'テキサスホールデムは、自分の手札2枚と、みんなで使う場の5枚から、いちばん強い5枚の役を作って競うポーカーです。',
        'このゲームはトーナメント形式です。全員が同じチップで始め、ハンドを重ねてチップを失った人から脱落し、最後に残った1人が優勝です。',
      ],
    },
    {
      title: 'ハンドの進み方',
      list: [
        '各自に手札が2枚ずつ配られます（他の人には見えません）。',
        'プリフロップ：最初のベッティング。',
        'フロップ：場に3枚が開き、ベッティング。',
        'ターン：4枚目が開き、ベッティング。',
        'リバー：5枚目が開き、最後のベッティング。',
        'ショーダウン：残った人が手札を公開し、いちばん強い役の人がポットを取ります。',
        '途中で全員が降りたら、残った1人が手札を見せずにポットを取ります。',
      ],
    },
    {
      title: 'ボタンとブラインド',
      paras: [
        'ハンドごとにディーラーボタンが左隣へ進みます。ボタンの左隣がスモールブラインド、その隣がビッグブラインドで、配る前に強制で少額を出します。',
        '2人のときは、ボタンの人がスモールブラインドを出し、プリフロップで先に動きます（フロップ以降はビッグブラインドが先）。',
        '3人以上のときは、プリフロップはビッグブラインドの左隣から、フロップ以降はボタンの左隣から時計回りに動きます。',
      ],
    },
    {
      title: 'ベッティング（ノーリミット）',
      list: [
        'フォールド：降りる。そのハンドでのチップは戻りません。',
        'チェック：誰もベットしていないとき、チップを出さずに次の人へ回す。',
        'ベット／コール：ベットされた額に合わせるのがコール。最初に出すのがベット。',
        'レイズ：ベットをさらに上げる。上げ幅は、直前のレイズ幅（最初はビッグブラインド）以上。上限はなく、手元のチップまで出せます。',
        'オールイン：手元のチップをすべて出す。足りない額でのコールもオールインです。',
        'レイズされたら、先に動いた人ももう一度行動できます。ただし、最小幅に満たないオールインでは、先に動いた人は再レイズできません（コールかフォールドのみ）。',
      ],
    },
    {
      title: '役の強さ（強い順）',
      list: [
        'ロイヤルフラッシュ：同じマークの 10・J・Q・K・A',
        'ストレートフラッシュ：同じマークで数字が5枚連続',
        'フォーカード：同じ数字4枚',
        'フルハウス：同じ数字3枚＋2枚',
        'フラッシュ：同じマーク5枚',
        'ストレート：数字が5枚連続（A は A-2-3-4-5 と 10-J-Q-K-A のどちらにも使えますが、K-A-2 のようにつなぐことはできません）',
        'スリーカード：同じ数字3枚',
        'ツーペア：同じ数字2枚が2組',
        'ワンペア：同じ数字2枚',
        'ハイカード：どれも成立しない（いちばん高い数字で比べる）',
        '同じ役のときは、役を作る数字の大きさ、次にキッカー（残りの高い数字）の順に比べます。5枚が完全に同じなら引き分けで、ポットを分けます。',
      ],
    },
    {
      title: 'オールインとサイドポット',
      paras: [
        'チップが足りない人がオールインしたとき、その人が争えるのは、自分が出した額までです。それを超えた分は「サイドポット」になり、残りの人だけで争います。',
        '誰にも受けてもらえなかったベット（相手のチップが少なかったときの差額）は、そのまま本人に戻ります。',
        'ポットを分けるときに割り切れない端数は、ボタンの左隣に近い勝者から1枚ずつ配られます。',
      ],
    },
    {
      title: 'ショーダウン',
      paras: [
        '最後のベッティングが終わったら、ボタンの左隣から順に手札を公開します（自動で公開されます）。',
        'ショーダウンで公開しない（スキップされた）人は、ポットを争う権利を失います。',
      ],
    },
    {
      title: 'トーナメントとブラインドの上昇',
      list: [
        `【この部屋の設定】最初のチップ ${fmt(o.startingChips)} 枚、${o.levelHands} ハンドごとにブラインドが上がります。`,
        `ブラインド（スモール/ビッグ）は ${levels} … のように上がり、最後のレベルのあとは倍々になります。`,
        'チップがなくなった人は脱落です。同じハンドで複数人が脱落したら、そのハンドの開始時にチップが多かった人が上位になります。',
        '最後の1人になったらトーナメント終了です。順位に応じた得点が通算に加わります。',
      ],
    },
    {
      title: '操作のしかた',
      list: [
        '自分の番になると、下に「フォールド」「チェック／コール」「ベット／レイズ」が出ます。',
        'ベット／レイズは、スライダーか数字で合計額を決めます。「最小」「½ポット」「ポット」「オールイン」のボタンで素早く入れられます。',
        '応答のない人がいるときは、ホストが「スキップ」できます（チェックできればチェック、できなければフォールド）。',
      ],
    },
  ];
}
